#!/usr/bin/env python3
"""Generate result tables and prose macros from one precision-level output."""
from pathlib import Path
import json
import pandas as pd

P=Path(__file__).resolve().parents[1];T=P/'tables'
s=json.loads((P/'data/results_summary.json').read_text())
e1=pd.DataFrame(s['E1']).set_index('method');e2=pd.DataFrame(s['E2']).set_index('condition')
macros={}


def table(name, columns, header, rows):
    text='\\begin{tabular}{'+columns+'}\n\\toprule\n'+header+' \\\\\n\\midrule\n'
    text+=''.join(' & '.join(str(x) for x in row)+' \\\\\n' for row in rows)
    (T/name).write_text(text+'\\bottomrule\n\\end{tabular}\n')


def number(name,value,digits=3):
    macros[name]=f'{value:.{digits}f}'


def mean_sd(row,key,digits):
    return f'${row[key+"_mean"]:.{digits}f} \\pm {row[key+"_sd"]:.{digits}f}$'


for method,row in e1.iterrows():
    for short,key,digits in [('Time','completion_time_s',3),('Excess','J_excess_Ns',3),('Peak','peak_Fz_base_N',2),('Travel','tcp_xy_distance_mm',2)]:
        number('Eone'+method+short,row[key+'_mean'],digits)
        number('Eone'+method+short+'SD',row[key+'_sd'],digits)
for condition,row in e2.iterrows():
    for short,key in [('Time','completion_time_corrected_s'),('Interval','execution_duration_s'),('MeanForce','mean_fz_N'),('Peak','peak_fz_N'),('Travel','tcp_xy_path_mm'),('ContactTime','time_fz_ge_3N_s'),('GateChanges','gate_transitions')]:
        number('Etwo'+condition+short,row[key+'_mean'],2)
        number('Etwo'+condition+short+'SD',row[key+'_sd'],2)
    macros['Etwo'+condition+'TimeN']=str(int(row['completion_time_corrected_s_n']))
for label,row in [('Cfive',s['E1_C5']),('Csix',s['C6'])]:
    for short,key in [('Time','completion_time_s'),('Excess','J_excess_Ns'),('Contact','contact_at_s'),('Pass','pass_completed_at_s'),('WorkZ','z_work_ref_mm'),('ReleaseZ','z_release_threshold_mm'),('ExcessTime','force_excess_duration_s')]:
        number(label+short,row[key],3)
    number(label+'Peak',row['peak_Fz_base_N'],2 if label=='Cfive' else 3)
number('BCSeconds',s['B_minus_C_seconds'],2);number('BCPercent',s['B_to_C_reduction_percent'],1)
number('ForceExposureReference',s['force_reference_upper_N'],9)
a4=pd.read_csv(P/'data/e2_runs_corrected.csv').query("label=='A4'").iloc[0]
for short,key in [('Interval','execution_duration_s'),('MeanForce','mean_fz_N'),('ContactTime','time_fz_ge_3N_s')]:
    number('Afour'+short,a4[key],3)
(T/'result_numbers.tex').write_text('% Generated by scripts/make_tables.py from data/results_summary.json.\n'+
    ''.join('\\newcommand{\\'+k+'}{'+v+'}\n' for k,v in macros.items()))

table('e1_primary.tex','lcrr',r'Method & Completed/started & Time (s) & $J_{\mathrm{excess}}$ (N\,s)',
      [[m,'5/5',mean_sd(e1.loc[m],'completion_time_s',3),mean_sd(e1.loc[m],'J_excess_Ns',3)] for m in ['R','T','C']])
table('e2_times.tex','lcrcr',r'Condition & \makecell{Completed/\\attempted} & \makecell{Completed\\time (s)} & $n$ & \makecell{All-attempt\\interval (s)}',
      [[m,f'{int(e2.loc[m,"completed"])}/5',mean_sd(e2.loc[m],'completion_time_corrected_s',2),int(e2.loc[m,'completion_time_corrected_s_n']),mean_sd(e2.loc[m],'execution_duration_s',2)] for m in ['A','B','C']])
table('e2_force_travel.tex','lrrr',r'Condition & Mean $F_z^B$ (N) & Peak $F_z^B$ (N) & XY travel (mm)',
      [[m,mean_sd(e2.loc[m],'mean_fz_N',2),mean_sd(e2.loc[m],'peak_fz_N',2),mean_sd(e2.loc[m],'tcp_xy_path_mm',2)] for m in ['A','B','C']])
a=pd.read_csv(P/'data/e1_runs.csv');b=pd.read_csv(P/'data/e2_runs_corrected.csv')
table('e1_all.tex','lcrrr',r'Run & Order & \makecell{Completion\\(s)} & \makecell{$J_{\mathrm{excess}}$\\(N\,s)} & \makecell{Peak $F_z^B$\\(N)}',
      [[r.label,int(r.execution_order),f'{r.completion_time_s:.3f}',f'{r.J_excess_Ns:.3f}',f'{r.peak_Fz_base_N:.2f}'] for method in ['R','T','C'] for _,r in a[a.method==method].sort_values('repeat_index').iterrows()])
table('e2_all.tex','llrr',r'Run & Task outcome & Completion (s) & Interval to stop (s)',
      [[r.label,'interrupted' if r.label=='A4' else 'operator completed',r'\NA' if pd.isna(r.completion_time_corrected_s) else f'{r.completion_time_corrected_s:.3f}',f'{r.execution_duration_s:.3f}'] for _,r in b.iterrows()])
c5,c6=s['E1_C5'],s['C6']
table('e1_c5_c6.tex','lrr',r'Metric & Original C5 (primary) & C6 (diagnostic)',
      [[name,f'{c5[key]:.{digits}f}',f'{c6[key]:.{digits}f}'] for name,key,digits in [
          ('Completion time (s)','completion_time_s',3),('First confirmed contact (s)','contact_at_s',3),
          ('Required pass complete (s)','pass_completed_at_s',3),('Working reference Z (mm)','z_work_ref_mm',3),
          ('Required exit Z (mm)','z_release_threshold_mm',3),('Observed peak force (N)','peak_Fz_base_N',3),
          (r'$J_{\mathrm{excess}}$ (N\,s)','J_excess_Ns',3),('Time above reference (s)','force_excess_duration_s',3),
          ('Recorded contact losses','contact_loss_count',0)]])
history=pd.read_csv(P/'data/history/e1_summary_20261014.csv').set_index('method')
table('e1_historical_primary.tex','lcrr',r'Method & Completed/started & Completed time (s) & $J_{\mathrm{excess}}$ (N\,s)',
      [[m,f'{int(history.loc[m,"completed"])}/5',mean_sd(history.loc[m],'completion_time_s',2),mean_sd(history.loc[m],'J_excess_Ns',3)] for m in ['R','T','C']])
replay=pd.read_csv(P/'data/e1_replay_summary.csv').set_index('method')
table('e1_replay.tex','lcr',r'Method & Replay completed & Replay time (s)',
      [[m,'5/5',mean_sd(replay.loc[m],'B_completion_time_s',2)] for m in ['R','T','C']])
print(f'Generated eight tables and {len(macros)} prose macros from precision-level CSV/JSON.')
